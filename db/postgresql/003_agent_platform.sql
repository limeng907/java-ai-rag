UPDATE interview_session SET status = 'REVIEW' WHERE status = 'IN_PROGRESS' AND turn_count >= 7;

CREATE TABLE interview_turn (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id BIGINT NOT NULL REFERENCES interview_session(id),
    request_id UUID NOT NULL,
    round_number INTEGER NOT NULL CHECK (round_number BETWEEN 1 AND 7),
    answer TEXT NOT NULL,
    question TEXT NOT NULL DEFAULT '',
    skipped BOOLEAN NOT NULL,
    status VARCHAR(20) NOT NULL CHECK (status IN ('PROCESSING','COMPLETED','FAILED')),
    score INTEGER CHECK (score BETWEEN 0 AND 100),
    correct BOOLEAN,
    complete BOOLEAN,
    need_follow_up BOOLEAN,
    missing_points JSONB NOT NULL DEFAULT '[]',
    result JSONB,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    completed_at TIMESTAMPTZ,
    UNIQUE (session_id, request_id)
);
CREATE UNIQUE INDEX idx_interview_turn_completed_round
    ON interview_turn(session_id, round_number) WHERE status = 'COMPLETED';
CREATE UNIQUE INDEX idx_interview_evaluation_unique_session ON interview_evaluation(session_id);

CREATE TABLE user_learning_profile (
    user_id BIGINT PRIMARY KEY REFERENCES app_user(id),
    target VARCHAR(200) NOT NULL DEFAULT 'Java backend',
    level VARCHAR(100) NOT NULL DEFAULT 'student',
    daily_minutes INTEGER NOT NULL DEFAULT 60 CHECK (daily_minutes BETWEEN 15 AND 480),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE agent_conversation (
    id UUID PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_user(id),
    kind VARCHAR(30) NOT NULL,
    busy_token UUID,
    busy_until TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_agent_conversation_user ON agent_conversation(user_id, created_at DESC);

CREATE TABLE agent_execution (
    id UUID PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_user(id),
    conversation_id UUID REFERENCES agent_conversation(id),
    session_id BIGINT REFERENCES interview_session(id),
    kind VARCHAR(30) NOT NULL,
    state VARCHAR(30) NOT NULL,
    prompt_version INTEGER NOT NULL,
    model_calls INTEGER NOT NULL DEFAULT 0,
    tool_calls INTEGER NOT NULL DEFAULT 0,
    error_code INTEGER,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    finished_at TIMESTAMPTZ
);
CREATE INDEX idx_agent_execution_user ON agent_execution(user_id, created_at DESC);
CREATE TABLE agent_tool_call (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    execution_id UUID NOT NULL REFERENCES agent_execution(id),
    tool_call_id VARCHAR(200) NOT NULL,
    tool_name VARCHAR(100) NOT NULL,
    input TEXT NOT NULL,
    output TEXT,
    status VARCHAR(20) NOT NULL,
    elapsed_ms BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE agent_message (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id UUID NOT NULL REFERENCES agent_conversation(id),
    execution_id UUID NOT NULL REFERENCES agent_execution(id),
    role VARCHAR(20) NOT NULL CHECK (role IN ('USER','ASSISTANT')),
    content TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_agent_message_conversation ON agent_message(conversation_id, id);

CREATE TABLE study_plan (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_user(id),
    conversation_id UUID NOT NULL REFERENCES agent_conversation(id),
    execution_id UUID NOT NULL REFERENCES agent_execution(id),
    content JSONB NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE prompt_template (
    name VARCHAR(50) NOT NULL,
