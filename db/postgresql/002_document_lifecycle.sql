BEGIN;

CREATE TABLE knowledge_base (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_user_id BIGINT NOT NULL REFERENCES app_user(id),
    name VARCHAR(200) NOT NULL,
    description TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (owner_user_id, name)
);

CREATE TABLE knowledge_document (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    knowledge_base_id BIGINT NOT NULL REFERENCES knowledge_base(id),
    owner_user_id BIGINT NOT NULL REFERENCES app_user(id),
    name VARCHAR(255) NOT NULL,
    status VARCHAR(30) NOT NULL,
    active_version INTEGER,
    latest_version INTEGER NOT NULL DEFAULT 0,
    error_message TEXT,
    retry_count INTEGER NOT NULL DEFAULT 0,
    last_failed_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    delete_requested_at TIMESTAMPTZ,
    deleted_at TIMESTAMPTZ
);

CREATE INDEX idx_knowledge_document_owner_base
    ON knowledge_document(owner_user_id, knowledge_base_id, id);
CREATE INDEX idx_knowledge_document_status
    ON knowledge_document(status, updated_at);

CREATE TABLE knowledge_document_version (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_id BIGINT NOT NULL REFERENCES knowledge_document(id),
    version INTEGER NOT NULL,
    original_name VARCHAR(255) NOT NULL,
    object_key VARCHAR(500) NOT NULL,
    file_type VARCHAR(20) NOT NULL,
    mime_type VARCHAR(100) NOT NULL,
    file_size BIGINT NOT NULL CHECK (file_size > 0),
    file_hash VARCHAR(64) NOT NULL,
    status VARCHAR(30) NOT NULL,
    chunk_count INTEGER NOT NULL DEFAULT 0,
    embedding_model VARCHAR(100),
    embedding_dimension INTEGER,
    chunk_strategy_version VARCHAR(50),
    parser_version VARCHAR(50),
    error_message TEXT,
    failed_stage VARCHAR(30),
    retry_count INTEGER NOT NULL DEFAULT 0,
    last_failed_at TIMESTAMPTZ,
    processing_token UUID,
    processing_started_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    processed_at TIMESTAMPTZ,
    UNIQUE (document_id, version)
);

CREATE INDEX idx_document_version_status
    ON knowledge_document_version(status, updated_at);
CREATE INDEX idx_document_version_hash
    ON knowledge_document_version(file_hash);
CREATE INDEX idx_document_version_document
    ON knowledge_document_version(document_id, version DESC);

COMMIT;
